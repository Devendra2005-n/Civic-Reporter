import { useState, useRef, useEffect } from 'react';
import { motion, AnimatePresence } from 'framer-motion';
import { MessageCircle, X, Send, Bot, User, Sparkles, Loader2, Trash2, Mic, MicOff } from 'lucide-react';
import { useLocation } from 'react-router-dom';
import { useAuth } from '../context/AuthContext';

const AIChatbot = () => {
  const location = useLocation();
  const hideOnPaths = ['/login', '/signup'];
  
  const { isAdmin } = useAuth();
  const [isOpen, setIsOpen] = useState(false);
  const [messages, setMessages] = useState([
    { 
      id: 1, 
      type: 'bot', 
      text: 'Hi! I\'m your Civic Reporter AI assistant. I can help you with:\n\n• Reporting issues\n• Tracking complaints\n• Understanding the process\n• Finding nearby authorities\n\nWhat can I help you with today?',
      timestamp: new Date()
    }
  ]);
  const [input, setInput] = useState('');
  const [isTyping, setIsTyping] = useState(false);
  const [isListening, setIsListening] = useState(false);
  const messagesEndRef = useRef(null);
  const inputRef = useRef(null);
  const recognitionRef = useRef(null);

  const scrollToBottom = () => {
    messagesEndRef.current?.scrollIntoView({ behavior: 'smooth' });
  };

  useEffect(() => {
    scrollToBottom();
  }, [messages, isOpen]);

  useEffect(() => {
    if (isOpen && inputRef.current) {
      inputRef.current.focus();
    }
  }, [isOpen]);

  // Initialize Speech Recognition
  useEffect(() => {
    const SpeechRecognition = window.SpeechRecognition || window.webkitSpeechRecognition;
    if (SpeechRecognition) {
      const recognition = new SpeechRecognition();
      recognition.continuous = false;
      recognition.interimResults = true;
      recognition.lang = 'en-IN'; // Support Indian English

      recognition.onresult = (event) => {
        let transcript = '';
        for (let i = event.resultIndex; i < event.results.length; i++) {
          transcript += event.results[i][0].transcript;
        }
        setInput(transcript);
        
        // If final result, auto-send
        if (event.results[event.results.length - 1].isFinal) {
          setIsListening(false);
        }
      };

      recognition.onerror = (event) => {
        console.error('Speech recognition error:', event.error);
        setIsListening(false);
      };

      recognition.onend = () => {
        setIsListening(false);
      };

      recognitionRef.current = recognition;
    }

    return () => {
      if (recognitionRef.current) {
        try { recognitionRef.current.stop(); } catch {}
      }
    };
  }, []);

  const toggleVoice = () => {
    if (!recognitionRef.current) {
      alert('Voice recognition is not supported in this browser. Please use Chrome or Edge.');
      return;
    }

    if (isListening) {
      recognitionRef.current.stop();
      setIsListening(false);
    } else {
      setInput('');
      recognitionRef.current.start();
      setIsListening(true);
    }
  };

  const handleSend = async () => {
    if (!input.trim()) return;

    const userMessage = {
      id: Date.now(),
      type: 'user',
      text: input,
      timestamp: new Date()
    };

    setMessages(prev => [...prev, userMessage]);
    const query = input.toLowerCase();
    setInput('');
    setIsTyping(true);

    // Smart response generation based on keywords
    setTimeout(() => {
      let responseText = '';

      if (query.includes('report') || query.includes('submit') || query.includes('complaint')) {
        responseText = "📝 To report an issue:\n\n1. Go to the Submit page\n2. Upload a photo of the problem\n3. Our AI will automatically detect the issue type\n4. Verify the details and submit\n\nYour complaint will be sent to the appropriate authority!";
      } else if (query.includes('track') || query.includes('status') || query.includes('my complaint')) {
        responseText = "📊 To track your complaints:\n\n1. Visit My Complaints from the menu\n2. You'll see all your submitted complaints with their current status\n3. Each complaint has a unique ID you can use to search\n\nStatus updates: Pending → In Progress → Resolved";
      } else if (query.includes('pdf') || query.includes('download') || query.includes('letter')) {
        responseText = "📄 You can download a formal complaint letter in PDF format after submitting your complaint. The letter is auto-generated by AI and addressed to the correct local authority.";
      } else if (query.includes('location') || query.includes('gps') || query.includes('where')) {
        responseText = "📍 The app automatically detects your location using GPS and identifies the correct authority (Gram Panchayat, Municipal Council, or Corporation). You can also drag the map pin to adjust the exact location.";
      } else if (query.includes('admin') || query.includes('authority')) {
        responseText = "🏛️ The system auto-detects the right authority based on your location:\n\n• 🏘️ Village → Gram Panchayat (Sarpanch)\n• 🏛️ Town → Municipal Council (Chief Officer)\n• 🏙️ City → Municipal Corporation (Commissioner)";
      } else if (query.includes('urgent') || query.includes('emergency') || query.includes('high priority')) {
        responseText = "🚨 For urgent issues:\n\n1. Set severity to High when submitting\n2. High severity complaints are prioritized by the admin\n3. Consider also contacting local emergency services (100/112) for immediate danger";
      } else if (query.includes('spam') || query.includes('fake') || query.includes('reputation')) {
        responseText = "🛡️ We have a multi-layer anti-spam system:\n\n• AI validates your image (rejects selfies, food, etc.)\n• Rate limit: Max 5 complaints/day\n• Reputation system: Valid complaints earn points, fake ones lose points\n• Admin moderation for flagged complaints";
      } else if (query.includes('translate') || query.includes('language') || query.includes('hindi')) {
        responseText = "🌐 We support 13 Indian languages! After the AI generates your complaint letter in English, you can translate it to Hindi, Marathi, Tamil, Telugu, and more using the language selector.";
      } else if (query.includes('hello') || query.includes('hi') || query.includes('hey')) {
        responseText = "👋 Hello! I'm your Civic Reporter AI assistant. How can I help you today? You can ask me about reporting issues, tracking complaints, or understanding how the system works!";
      } else if (query.includes('thank') || query.includes('thanks')) {
        responseText = "😊 You're welcome! Happy to help. If you have any other questions, feel free to ask anytime!";
      } else {
        responseText = "I can help you with:\n\n• 📝 Reporting issues — how to submit complaints\n• 📊 Tracking status — check your complaint progress\n• 📍 Location — how GPS detection works\n• 🏛️ Authorities — who handles your complaint\n• 🛡️ Anti-spam — our verification system\n• 🌐 Translation — available languages\n\nTry asking about any of these topics!";
      }
      
      const botResponse = {
        id: Date.now() + 1,
        type: 'bot',
        text: responseText,
        timestamp: new Date()
      };
      
      setMessages(prev => [...prev, botResponse]);
      setIsTyping(false);
    }, 800 + Math.random() * 700);
  };

  const handleKeyPress = (e) => {
    if (e.key === 'Enter' && !e.shiftKey) {
      e.preventDefault();
      handleSend();
    }
  };

  const clearChat = () => {
    setMessages([{
      id: Date.now(),
      type: 'bot',
      text: 'Chat cleared! How can I help you today?',
      timestamp: new Date()
    }]);
  };

  if (isAdmin || hideOnPaths.includes(location.pathname)) return null;

  return (
    <>
      {/* Floating Toggle Button — RIGHT CORNER */}
      <AnimatePresence>
        {!isOpen && (
          <motion.button
            initial={{ scale: 0, opacity: 0 }}
            animate={{ scale: 1, opacity: 1 }}
            exit={{ scale: 0, opacity: 0 }}
            transition={{ type: 'spring', stiffness: 300, damping: 20 }}
            onClick={() => setIsOpen(true)}
            className="fixed bottom-5 right-5 sm:bottom-8 sm:right-8 z-40 group cursor-pointer"
            whileHover={{ scale: 1.08 }}
            whileTap={{ scale: 0.95 }}
          >
            <div className="relative w-14 h-14 bg-[#0284C7] hover:bg-[#0369A1] rounded-full shadow-lg shadow-sky-600/25 flex items-center justify-center text-white border-2 border-white transition-colors">
              <MessageCircle className="w-6 h-6 text-white" />
              <span className="absolute top-0 right-0 w-3.5 h-3.5 bg-[#16A34A] border-2 border-white rounded-full" />
            </div>
          </motion.button>
        )}
      </AnimatePresence>

      {/* Chat Window — RIGHT CORNER */}
      <AnimatePresence>
        {isOpen && (
          <motion.div
            initial={{ opacity: 0, scale: 0.95, y: 16 }}
            animate={{ opacity: 1, scale: 1, y: 0 }}
            exit={{ opacity: 0, scale: 0.95, y: 16 }}
            transition={{ type: 'spring', stiffness: 300, damping: 25 }}
            className="fixed bottom-4 right-4 sm:bottom-8 sm:right-8 w-[calc(100vw-2rem)] sm:w-[390px] h-[520px] sm:h-[550px] z-50"
          >
            <div className="relative w-full h-full bg-white rounded-2xl border border-[#E5E7EB] shadow-2xl overflow-hidden flex flex-col text-[#334155]">
              
              {/* Header */}
              <div className="flex items-center justify-between px-5 py-3.5 bg-white border-b border-[#E5E7EB]">
                <div className="flex items-center gap-3">
                  <div className="w-9 h-9 rounded-xl bg-[#F0F9FF] border border-[#BAE6FD] flex items-center justify-center text-[#0284C7]">
                    <Bot className="w-5 h-5" />
                  </div>
                  <div>
                    <h3 className="font-bold text-[#0F172A] text-sm leading-tight">Civic Assistant</h3>
                    <div className="flex items-center gap-1.5 mt-0.5">
                      <div className="w-2 h-2 bg-[#16A34A] rounded-full" />
                      <span className="text-[11px] text-[#6B7280]">Online • Ready to help</span>
                    </div>
                  </div>
                </div>
                
                <div className="flex items-center gap-1">
                  <button
                    onClick={clearChat}
                    className="p-1.5 rounded-lg text-[#9CA3AF] hover:text-[#0F172A] hover:bg-[#F3F4F6] transition-colors"
                    title="Clear chat"
                  >
                    <Trash2 className="w-4 h-4" />
                  </button>
                  <button
                    onClick={() => setIsOpen(false)}
                    className="p-1.5 rounded-lg text-[#9CA3AF] hover:text-[#0F172A] hover:bg-[#F3F4F6] transition-colors"
                    title="Close"
                  >
                    <X className="w-4 h-4" />
                  </button>
                </div>
              </div>

              {/* Messages Body */}
              <div className="flex-1 overflow-y-auto p-4 space-y-3.5 bg-[#F9FAFB] custom-scrollbar">
                {messages.map((msg) => (
                  <motion.div
                    key={msg.id}
                    initial={{ opacity: 0, y: 6 }}
                    animate={{ opacity: 1, y: 0 }}
                    className={`flex ${msg.type === 'user' ? 'justify-end' : 'justify-start'}`}
                  >
                    <div className={`flex gap-2 max-w-[85%] ${msg.type === 'user' ? 'flex-row-reverse' : ''}`}>
                      <div className={`w-7 h-7 rounded-lg flex items-center justify-center shrink-0 text-xs font-semibold ${
                        msg.type === 'user'
                          ? 'bg-[#E0F2FE] text-[#0284C7]'
                          : 'bg-white border border-[#E5E7EB] text-[#0284C7]'
                      }`}>
                        {msg.type === 'user' ? <User className="w-3.5 h-3.5" /> : <Bot className="w-3.5 h-3.5" />}
                      </div>
                      
                      <div className={`px-3.5 py-2.5 rounded-2xl text-xs sm:text-sm leading-relaxed whitespace-pre-wrap shadow-xs ${
                        msg.type === 'user'
                          ? 'bg-[#0284C7] text-white rounded-br-xs font-normal'
                          : 'bg-white text-[#334155] border border-[#E5E7EB] rounded-bl-xs'
                      }`}>
                        {msg.text}
                      </div>
                    </div>
                  </motion.div>
                ))}
                
                {/* Typing indicator */}
                {isTyping && (
                  <div className="flex justify-start">
                    <div className="flex gap-2 items-center">
                      <div className="w-7 h-7 rounded-lg bg-white border border-[#E5E7EB] flex items-center justify-center text-[#0284C7]">
                        <Bot className="w-3.5 h-3.5" />
                      </div>
                      <div className="px-3 py-2 rounded-2xl bg-white border border-[#E5E7EB] rounded-bl-xs shadow-xs">
                        <div className="flex gap-1">
                          {[0, 1, 2].map((i) => (
                            <motion.div
                              key={i}
                              className="w-1.5 h-1.5 bg-[#0284C7] rounded-full"
                              animate={{ y: [0, -4, 0] }}
                              transition={{ duration: 0.6, repeat: Infinity, delay: i * 0.12 }}
                            />
                          ))}
                        </div>
                      </div>
                    </div>
                  </div>
                )}
                <div ref={messagesEndRef} />
              </div>

              {/* Input Footer */}
              <div className="p-3 bg-white border-t border-[#E5E7EB]">
                {/* Voice Recording Indicator */}
                <AnimatePresence>
                  {isListening && (
                    <motion.div
                      initial={{ opacity: 0, height: 0 }}
                      animate={{ opacity: 1, height: 'auto' }}
                      exit={{ opacity: 0, height: 0 }}
                      className="mb-2.5 flex items-center gap-2.5 px-3 py-1.5 rounded-lg bg-[#FEF2F2] border border-[#FECACA]"
                    >
                      <div className="w-2 h-2 bg-[#DC2626] rounded-full animate-ping" />
                      <span className="text-xs text-[#DC2626] font-medium">Listening... speak your issue</span>
                    </motion.div>
                  )}
                </AnimatePresence>

                <div className="flex gap-2 items-center">
                  {/* Voice Button */}
                  <button
                    type="button"
                    onClick={toggleVoice}
                    className={`p-2 rounded-xl border transition-colors flex items-center justify-center ${
                      isListening
                        ? 'bg-[#FEF2F2] text-[#DC2626] border-[#FECACA]'
                        : 'border-[#D1D5DB] text-[#6B7280] hover:text-[#0284C7] hover:border-[#BAE6FD] hover:bg-[#F0F9FF]'
                    }`}
                    title={isListening ? "Stop listening" : "Voice input"}
                  >
                    {isListening ? <MicOff className="w-4 h-4" /> : <Mic className="w-4 h-4" />}
                  </button>

                  <div className="flex-1 relative">
                    <input
                      ref={inputRef}
                      type="text"
                      value={input}
                      onChange={(e) => setInput(e.target.value)}
                      onKeyPress={handleKeyPress}
                      placeholder={isListening ? "Listening..." : "Ask a question..."}
                      className="w-full bg-[#F9FAFB] border border-[#D1D5DB] rounded-xl px-3.5 py-2 text-xs sm:text-sm text-[#0F172A] placeholder-[#9CA3AF] focus:outline-none focus:bg-white focus:border-[#0284C7] focus:ring-2 focus:ring-[#0284C7]/20 transition-all"
                    />
                  </div>

                  <button
                    type="button"
                    onClick={handleSend}
                    disabled={!input.trim() || isTyping}
                    className="p-2 rounded-xl bg-[#0284C7] hover:bg-[#0369A1] text-white transition-colors disabled:opacity-40 disabled:cursor-not-allowed shadow-xs"
                  >
                    {isTyping ? <Loader2 className="w-4 h-4 animate-spin" /> : <Send className="w-4 h-4" />}
                  </button>
                </div>
                
                {/* Quick suggestions */}
                <div className="flex gap-1.5 mt-2 overflow-x-auto pb-0.5 custom-scrollbar">
                  {['How to report?', 'Track complaint', 'Anti-spam system', 'Download letter'].map((suggestion) => (
                    <button
                      key={suggestion}
                      onClick={() => setInput(suggestion)}
                      className="shrink-0 px-2.5 py-1 rounded-full bg-[#F3F4F6] border border-[#E5E7EB] text-[11px] text-[#4B5563] hover:text-[#0284C7] hover:border-[#BAE6FD] hover:bg-[#F0F9FF] transition-all whitespace-nowrap"
                    >
                      {suggestion}
                    </button>
                  ))}
                </div>
              </div>

            </div>
          </motion.div>
        )}
      </AnimatePresence>
    </>
  );
};

export default AIChatbot;
